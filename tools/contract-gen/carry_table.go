package main

import (
	"bytes"
	"encoding/json"
	"fmt"

	"github.com/sainteye/clawdline/internal/domain/cloudvocab"
)

// renderCarryTable is web/console/src/cloud/carry-generated.ts: the console's
// three word lists, read from the same vocabulary table the machine's decoders
// are generated from. What the console does with them — the reader's drift
// check, the refusal sentences, the uncarried routes it names — stays in the
// hand-written carry.ts, which imports these.
//
// The lists keep the table's order, sorted by word, and each row's
// `console_note` is the comment above its entry.
func renderCarryTable(ops []cloudvocab.Operation) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/contract-gen from internal/domain/cloudvocab/vocabulary.json; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// The console's three word lists. Why they are lists, and what reads them, is\n")
	b.WriteString("// at the top of carry.ts. To change one, edit the row in the table and run\n")
	b.WriteString("// `go run ./tools/contract-gen`. Nothing is imported here, so both the console\n")
	b.WriteString("// and `node --test` read it as it is.\n\n")

	lists := []struct {
		name    string
		console cloudvocab.Console
		doc     string
	}{
		{"CARRIED", cloudvocab.Carried, "The words this console asks a machine for, and the console route that asks (the row's `console_route`). The value is documentation and the key is the contract: `writeRoute` and the reader's own cases name these keys, and TypeScript refuses a word that is not one of them."},
		{"DEFERRED", cloudvocab.Deferred, "Words this machine answers that this console does not ask for yet, each with what a person reading the refusal needs: what is missing and where the thing can be done instead (the row's `console_sentence`)."},
		{"NO_MACHINE_ROUTE", cloudvocab.NoMachineRoute, "Words the machine knows and has nothing behind. Asking for one is answered `unknown_command` by the bridge, so the console does not ask: the sentence (the row's `console_sentence`) is what it says instead."},
	}
	for i, list := range lists {
		if i > 0 {
			b.WriteString("\n")
		}
		b.WriteString(jsdoc(list.doc, ""))
		fmt.Fprintf(&b, "export const %s = {\n", list.name)
		n := 0
		for _, o := range ops {
			if o.Console != list.console {
				continue
			}
			value := o.ConsoleRoute
			if list.console != cloudvocab.Carried {
				value = o.ConsoleSentence
			}
			literal, err := tsString(value)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", o.Op, err)
			}
			b.WriteString(wrap(o.ConsoleNote, "  // ", 80))
			fmt.Fprintf(&b, "  %s: %s,\n", tsProp(o.Op), literal)
			n++
		}
		if n == 0 {
			// An empty list would type its words as `never` and agree with
			// nothing; a table that empties one is a table to look at.
			return nil, fmt.Errorf("the table has no %s words", list.console)
		}
		b.WriteString("} as const\n")
	}

	b.WriteString("\n/** One word of the machine's Cloud vocabulary. */\n")
	b.WriteString("export type CloudWord = CarriedWord | keyof typeof DEFERRED | keyof typeof NO_MACHINE_ROUTE\n\n")
	b.WriteString(jsdoc("A word this console asks a machine for. `relay-writer.ts` declares each of its routes' words through this type, so a route that names a word missing from `CARRIED` is a compile error rather than another place the vocabulary is written down.", ""))
	b.WriteString("export type CarriedWord = keyof typeof CARRIED\n")
	return b.Bytes(), nil
}

// tsString is a double-quoted TypeScript string literal: JSON's, without the
// HTML escaping that would turn `<` and `&` into escapes a reader has to decode.
func tsString(s string) (string, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(s); err != nil {
		return "", err
	}
	return string(bytes.TrimSuffix(b.Bytes(), []byte("\n"))), nil
}
