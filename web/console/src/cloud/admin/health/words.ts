export type HealthLocale = "en" | "zh-TW"
export type HealthSay = (key: HealthWord, values?: Record<string, string | number>) => string

const TABLES: Record<HealthLocale, Record<HealthWord, string>> = { en, "zh-TW": zhTW }

export function healthWords(locale?: HealthLocale): HealthSay {
  const table = locale ? TABLES[locale] : null
  return (key, values) => (table ? table[key] : catalogWord("health", key) as string).replace(/\{(\w+)\}/g, (whole, name: string) => (values && name in values ? String(values[name]) : whole))
}

/** Every key, for tests that check both tables carry the same placeholders. */
export const HEALTH_WORD_TABLES = TABLES

/** A whole-unit duration: "12 s", "3 min", "2 h", "4 d". Null is the word for unknown. */
export function healthDuration(say: HealthSay, seconds: number | null): string {
  if (seconds === null || !Number.isFinite(seconds)) return say("unknown")
  const s = Math.max(0, Math.round(seconds))
  if (s < 60) return say("dur_s", { n: s })
  if (s < 3600) return say("dur_min", { n: Math.floor(s / 60) })
  if (s < 86400) return say("dur_h", { n: Math.floor(s / 3600) })
  return say("dur_d", { n: Math.floor(s / 86400) })
}

export function healthMs(say: HealthSay, ms: number | null): string {
  if (ms === null) return say("unknown")
  return ms >= 10_000 ? say("dur_s", { n: Math.round(ms / 1000) }) : say("ms", { n: Math.round(ms) })
}

/** "HH:MM" in UTC; the screens always add the zone word themselves. */
export function healthClock(iso: string): string {
  const d = new Date(iso)
  return `${String(d.getUTCHours()).padStart(2, "0")}:${String(d.getUTCMinutes()).padStart(2, "0")}`
}
