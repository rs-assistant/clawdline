export type SurveyWord = keyof typeof surveyEn
export function surveyWord(key: SurveyWord, values?: Record<string, string | number>): string {
  return catalogWord("survey", key).replace(/\{(\w+)\}/g, (whole, name: string) => values && name in values ? String(values[name]) : whole)
}
